  <div class="materi-text">
    <h4>🌿 Apa itu Konservasi?</h4>

    <p>
      Alam menyediakan berbagai sumber daya yang penting bagi kehidupan
      manusia, seperti udara bersih, air, makanan, dan berbagai bahan
      alam lainnya. Namun, aktivitas manusia yang berlebihan dapat
      menyebabkan kerusakan lingkungan dan bahkan kepunahan makhluk hidup.
    </p>

    <p>
      Oleh karena itu diperlukan suatu upaya untuk menjaga dan
      melestarikan alam. Upaya tersebut disebut <strong>konservasi</strong>.
    </p>

    <p>
      Konservasi adalah usaha untuk melindungi, menjaga,
      serta mengelola sumber daya alam secara bijaksana
      agar tetap tersedia bagi generasi sekarang
      maupun generasi yang akan datang.
    </p>
  </div>
</article>


