  </p>



<!-- ================= MANFAAT EKOLOGI ================= -->
<article class="materi-block fade-section">

  <div class="materi-text">
    <h4>🌳 1. Manfaat Ekologi</h4>

    <p>
      Dari sisi ekologi, konservasi membantu menjaga
      keseimbangan ekosistem di alam.
      Dengan menjaga kelestarian tumbuhan,
      hewan, serta habitatnya,
      berbagai proses alami dapat tetap berlangsung dengan baik.
    </p>

    <ul>
      <li>Menjaga keseimbangan ekosistem.</li>
      <li>Mencegah kepunahan berbagai spesies.</li>
      <li>Menjaga keberlangsungan rantai makanan.</li>
      <li>Mengurangi risiko bencana alam seperti banjir dan longsor.</li>
      <li>Menjaga kualitas udara, tanah, dan air.</li>
    </ul>

    <p>
      Jika keanekaragaman hayati tetap terjaga,
      maka lingkungan akan menjadi lebih stabil
      dan mampu mendukung kehidupan berbagai makhluk hidup.
    </p>
  </div>
</article>



<!-- ================= MANFAAT EKONOMI ================= -->
<article class="materi-block reverse fade-section">

  <div class="materi-text">
    <h4>💰 2. Manfaat Ekonomi</h4>

    <p>
      Selain memberikan manfaat bagi lingkungan,
      konservasi juga memberikan manfaat ekonomi bagi manusia.
      Sumber daya alam yang dikelola secara bijaksana
      dapat dimanfaatkan secara berkelanjutan.
    </p>

    <ul>
      <li>Menyediakan sumber pangan bagi manusia.</li>
      <li>Menyediakan bahan baku obat-obatan.</li>
      <li>Menyediakan bahan baku industri.</li>
      <li>Mendukung kegiatan pariwisata alam (ekowisata).</li>
    </ul>

    <p>
      Kawasan konservasi seperti taman nasional
      sering dijadikan tempat wisata alam.
      Hal ini dapat memberikan pendapatan
      bagi masyarakat sekitar sekaligus meningkatkan
      kesadaran untuk menjaga lingkungan.
    </p>
  </div>
</article>



